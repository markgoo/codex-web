#!/usr/bin/env pwsh
# Starts codex-web and nginx without any console window, at logon, as this user.
#
#   pwsh -File deploy/autostart.ps1 status
#   pwsh -File deploy/autostart.ps1 install      # default: startup folder
#   pwsh -File deploy/autostart.ps1 uninstall
#
# Two mechanisms, both run as the signed-in user:
#
#   startup (default)  a .vbs in the Startup folder launches a hidden pwsh.
#                      Needs no elevation and works on machines where task
#                      registration is refused (this one: `schtasks /create`
#                      returns Access denied even elevated).
#   task               a "run at logon" scheduled task with restart-on-failure.
#                      Better supervision, but the Task Scheduler refused it
#                      here, so it is opt-in.
#
# Not a Windows service on purpose: as SYSTEM the server cannot see
# %USERPROFILE%\.codex (Codex login, threads, config.toml), so it would start
# with no account and no history.
#
# Logs: each launcher appends to scratch/logs/<script>.log, so hiding the
# console does not lose the output.

[CmdletBinding()]
param(
  [ValidateSet("status", "install", "uninstall")]
  [string]$Action = "status",
  [ValidateSet("startup", "task")]
  [string]$Method = "startup",
  [string]$Repo = (Split-Path -Parent $PSScriptRoot),
  [int]$NginxDelaySeconds = 30
)

$ErrorActionPreference = "Stop"

$items = @(
  @{ Key = "codex-web"; Script = "run-server.ps1"; DelaySeconds = 0; TaskName = "codex-web" },
  @{ Key = "codex-web-nginx"; Script = "nginx.ps1"; DelaySeconds = $NginxDelaySeconds; TaskName = "codex-web-nginx" }
)

$autostartDir = Join-Path $Repo "scratch\autostart"
$logDir = Join-Path $Repo "scratch\logs"
$startupDir = [Environment]::GetFolderPath("Startup")

function Get-PwshPath {
  $candidate = Join-Path $PSHOME "pwsh.exe"
  if (Test-Path $candidate) { return $candidate }
  $found = (Get-Command pwsh.exe -ErrorAction SilentlyContinue).Source
  if ($found) { return $found }
  throw "pwsh.exe not found (PowerShell 7 required)"
}

# A launcher that redirects the real script's output to a log file.
function Write-Launcher([string]$scriptName) {
  New-Item -ItemType Directory -Force -Path $autostartDir, $logDir | Out-Null
  $base = [IO.Path]::GetFileNameWithoutExtension($scriptName)
  $launcher = Join-Path $autostartDir "$base.ps1"
  $log = Join-Path $logDir "$base.log"
  $target = Join-Path $Repo "deploy\$scriptName"
  $body = @"
# generated by deploy/autostart.ps1 - edit that script, not this file
`$ErrorActionPreference = 'Continue'
`$log = '$log'
(New-Item -ItemType Directory -Force -Path (Split-Path -Parent `$log) | Out-Null)
"[{0}] starting $scriptName" -f (Get-Date -Format s) | Out-File -Append -Encoding utf8 `$log
& '$target' *>> `$log
"[{0}] $scriptName exited code=`$LASTEXITCODE" -f (Get-Date -Format s) | Out-File -Append -Encoding utf8 `$log
"@
  Set-Content -Path $launcher -Value $body -Encoding utf8
  return $launcher
}

# WScript runs the launcher fully hidden (0 = no window), so nothing flashes.
function Write-Vbs([hashtable]$item, [string]$launcher) {
  $pwsh = Get-PwshPath
  $vbs = Join-Path $autostartDir ("{0}.vbs" -f $item.Key)
  $command = '"{0}" -NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File "{1}"' -f $pwsh, $launcher
  $lines = @(
    "' generated by deploy/autostart.ps1"
    "Dim sh : Set sh = CreateObject(`"WScript.Shell`")"
  )
  if ($item.DelaySeconds -gt 0) {
    # nginx proxies to 127.0.0.1:8214, so wait for the server to come up.
    $lines += "WScript.Sleep {0}" -f ($item.DelaySeconds * 1000)
  }
  $lines += "sh.Run `"{0}`", 0, False" -f $command.Replace('"', '""')
  Set-Content -Path $vbs -Value $lines -Encoding ascii
  return $vbs
}

function Get-StartupPath([hashtable]$item) {
  Join-Path $startupDir ("{0}.vbs" -f $item.Key)
}

switch ($Action) {
  "status" {
    Write-Host "repo    : $Repo"
    Write-Host "startup : $startupDir"
    Write-Host "logs    : $logDir"
    foreach ($item in $items) {
      $inStartup = Test-Path (Get-StartupPath $item)
      $task = Get-ScheduledTask -TaskName $item.TaskName -ErrorAction SilentlyContinue
      Write-Host ("{0,-16} startup={1} task={2}" -f `
        $item.Key, $(if ($inStartup) { "yes" } else { "no" }), $(if ($task) { $task.State } else { "no" }))
    }
    if (Test-Path $logDir) {
      Get-ChildItem $logDir -Filter *.log -ErrorAction SilentlyContinue |
        Select-Object Name, Length, LastWriteTime | Format-Table -AutoSize |
        Out-String -Width 100 | Write-Host
    }
  }

  "install" {
    foreach ($item in $items) {
      $launcher = Write-Launcher $item.Script
      $vbs = Write-Vbs $item $launcher
      if ($Method -eq "startup") {
        New-Item -ItemType Directory -Force -Path $startupDir | Out-Null
        Copy-Item $vbs (Get-StartupPath $item) -Force
        Write-Host ("installed {0,-16} -> {1}" -f $item.Key, (Get-StartupPath $item))
      } else {
        $pwsh = Get-PwshPath
        $taskAction = New-ScheduledTaskAction -Execute $pwsh `
          -Argument "-NoProfile -WindowStyle Hidden -ExecutionPolicy Bypass -File `"$launcher`"" `
          -WorkingDirectory $Repo
        $trigger = New-ScheduledTaskTrigger -AtLogOn
        if ($item.DelaySeconds -gt 0) { $trigger.Delay = "PT$($item.DelaySeconds)S" }
        $settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries `
          -DontStopIfGoingOnBatteries -StartWhenAvailable -MultipleInstances IgnoreNew `
          -ExecutionTimeLimit (New-TimeSpan -Seconds 0) `
          -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
        Register-ScheduledTask -TaskName $item.TaskName -Action $taskAction -Trigger $trigger `
          -Settings $settings -Description "codex-web autostart ($($item.Script))" -Force | Out-Null
        Write-Host ("installed {0,-16} -> scheduled task" -f $item.Key)
      }
    }
    Write-Host ""
    Write-Host "next logon starts both with no window. run now:"
    foreach ($item in $items) {
      if ($Method -eq "startup") {
        Write-Host ("  wscript.exe `"{0}`"" -f (Get-StartupPath $item))
      } else {
        Write-Host ("  Start-ScheduledTask -TaskName {0}" -f $item.TaskName)
      }
    }
    Write-Host "logs: $logDir"
  }

  "uninstall" {
    foreach ($item in $items) {
      $startupPath = Get-StartupPath $item
      if (Test-Path $startupPath) {
        Remove-Item $startupPath -Force
        Write-Host "removed $startupPath"
      }
      $task = Get-ScheduledTask -TaskName $item.TaskName -ErrorAction SilentlyContinue
      if ($task) {
        Unregister-ScheduledTask -TaskName $item.TaskName -Confirm:$false
        Write-Host "removed task $($item.TaskName)"
      }
    }
  }
}
